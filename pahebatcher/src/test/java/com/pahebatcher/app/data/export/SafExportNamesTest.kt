package com.pahebatcher.app.data.export

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Pure display-name rules for
 * the SAF export path. These are the §36 unit-test surface for the collision
 * and `.pb.part` ownership contracts that [SafExporter] relies on.
 */
class SafExportNamesTest {

    // ------------------------------------------------------------------
    // 104.6 comparison key: NFC + case-insensitive over the WHOLE name
    // ------------------------------------------------------------------

    @Test
    fun `key is case-insensitive across the whole name including extension`() {
        assertEquals(SafExportNames.key("Ep 01.mp4"), SafExportNames.key("EP 01.MP4"))
        assertTrue(SafExportNames.key("Ep01.MP4") != SafExportNames.key("Ep01.mkv"))
    }

    @Test
    fun `key normalizes NFC so composed and decomposed names match`() {
        // "é" as U+00E9 vs "e" + combining acute U+0301.
        val composed = "Caf\u00E9 Ep 01.mp4"
        val decomposed = "Cafe\u0301 Ep 01.mp4"
        assertTrue(
            "NFC-normalized keys must be equal",
            SafExportNames.key(composed) == SafExportNames.key(decomposed),
        )
    }

    // ------------------------------------------------------------------
    // 104.1 / 104.3 part ownership
    // ------------------------------------------------------------------

    @Test
    fun `isPart recognises only the application suffix`() {
        assertTrue(SafExportNames.isPart("Ep 01.mp4.pb.part"))
        assertTrue(SafExportNames.isPart(SafExportNames.PART_SUFFIX))
        assertFalse(SafExportNames.isPart("Ep 01.mp4"))
        assertFalse(SafExportNames.isPart("Ep 01.part"))
        assertFalse(SafExportNames.isPart("Ep 01.mp4.tmp"))
    }

    @Test
    fun `partTarget strips exactly the application suffix`() {
        assertEquals(
            "Ep 01.mp4",
            SafExportNames.partTarget("Ep 01.mp4" + SafExportNames.PART_SUFFIX),
        )
        // A final name without the suffix is returned unchanged.
        assertEquals("Ep 01.mp4", SafExportNames.partTarget("Ep 01.mp4"))
    }

    @Test
    fun `isOurs matches the exact name case-insensitively`() {
        assertTrue(SafExportNames.isOurs("Ep 01.mp4", "EP 01.MP4"))
        assertFalse(SafExportNames.isOurs("Ep 02.mp4", "Ep 01.mp4"))
    }

    @Test
    fun `isOurs matches NFC variants of the expected name`() {
        assertTrue(
            SafExportNames.isOurs("Cafe\u0301 Ep 01.mp4", "Caf\u00E9 Ep 01.mp4"),
        )
    }

    @Test
    fun `isOurs accepts the uniquified n-suffix form of the expected name`() {
        // Generated by the collision rule on a previous export (104.3/104.5).
        assertTrue(SafExportNames.isOurs("Ep 01 (2).mp4", "Ep 01.mp4"))
        assertTrue(SafExportNames.isOurs("Ep 01 (99).mp4", "Ep 01.mp4"))
        // Case-insensitive too.
        assertTrue(SafExportNames.isOurs("EP 01 (2).MP4", "ep 01.mp4"))
    }

    @Test
    fun `isOurs rejects another episode's n-suffix form`() {
        assertFalse(SafExportNames.isOurs("Ep 02 (2).mp4", "Ep 01.mp4"))
        assertFalse(SafExportNames.isOurs("Different Show (2).mp4", "Ep 01.mp4"))
    }

    @Test
    fun `isOurs never invents ownership for extension-less names`() {
        // The (n) rule only applies to names with an extension; extension-less
        // collisions can only match exactly.
        assertFalse(SafExportNames.isOurs("Episode (2)", "Episode"))
        assertTrue(SafExportNames.isOurs("episode", "Episode"))
    }

    // ------------------------------------------------------------------
    // 104.6 uniquify: first free `<base> (n).<ext>` with n ≥ 2
    // ------------------------------------------------------------------

    @Test
    fun `uniquify returns the requested name when its key is unused`() {
        val existing = listOf("Other.mp4")
        assertEquals(
            "Ep 01.mp4",
            SafExportNames.uniquify("Ep 01.mp4", existing),
        )
    }

    @Test
    fun `uniquify appends the first free n starting at 2`() {
        val existing = listOf("Ep 01.mp4")
        assertEquals(
            "Ep 01 (2).mp4",
            SafExportNames.uniquify("Ep 01.mp4", existing),
        )
    }

    @Test
    fun `uniquify skips taken n suffixes`() {
        val existing = listOf("Ep 01.mp4", "Ep 01 (2).mp4", "EP 01 (3).MP4")
        assertEquals(
            "Ep 01 (4).mp4",
            SafExportNames.uniquify("Ep 01.mp4", existing),
        )
    }

    @Test
    fun `uniquify treats case differences as collisions`() {
        val existing = listOf("EP 01.MP4")
        assertEquals(
            "Ep 01 (2).mp4",
            SafExportNames.uniquify("Ep 01.mp4", existing),
        )
    }

    @Test
    fun `uniquify treats NFC variants as collisions`() {
        val existing = listOf("Caf\u00E9 Ep 01.mp4")
        assertEquals(
            "Cafe\u0301 Ep 01 (2).mp4",
            SafExportNames.uniquify("Cafe\u0301 Ep 01.mp4", existing),
        )
    }

    @Test
    fun `uniquify keeps the final extension when the name has multiple dots`() {
        val existing = listOf("Show Ep 01.1080p.mp4")
        assertEquals(
            "Show Ep 01.1080p (2).mp4",
            SafExportNames.uniquify("Show Ep 01.1080p.mp4", existing),
        )
    }

    @Test
    fun `uniquify handles names without an extension`() {
        val existing = listOf("Readme")
        assertEquals("Readme (2)", SafExportNames.uniquify("Readme", existing))
    }
}
